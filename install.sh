#!/usr/bin/env bash
# Wheelwright Workshop Orders — install, migrate and seed.
# Installs project-level Python dependencies only, then exits.
# The server is started separately (see README / INSTALL.md).
set -euo pipefail
cd "$(dirname "$0")"

PYTHON="${PYTHON:-python3}"

echo "==> Upgrading pip tooling"
"$PYTHON" -m pip install --upgrade pip setuptools wheel >/dev/null 2>&1 || \
  echo "    (pip tooling upgrade skipped; continuing with the installed tooling)"

echo "==> Installing Python dependencies from requirements.txt"
if ! "$PYTHON" -m pip install -r requirements.txt; then
  echo "    retrying with --user"
  "$PYTHON" -m pip install --user -r requirements.txt
fi

if [ ! -f .env ]; then
  echo "==> Writing .env with a generated session secret"
  secret="$("$PYTHON" -c 'import secrets; print(secrets.token_hex(32))')"
  cat > .env <<EOF
# Local development configuration (generated by install.sh).
# Never commit this file. Delete it to fall back to the built-in dev secret.
SESSION_SECRET=${secret}
DATABASE_URL=sqlite:///./wheelwright.db
SESSION_COOKIE_NAME=wheelwright_session
SESSION_MAX_AGE=43200
COOKIE_SECURE=false
EOF
else
  echo "==> Keeping the existing .env"
fi

echo "==> Creating the SQLite schema and loading demo workshop data"
"$PYTHON" -m app.seed

echo "==> Verifying the application imports cleanly"
"$PYTHON" -c "import app.main"

cat <<'DONE'

Install complete.
Start the workshop with:
  uvicorn app.main:app --host 0.0.0.0 --port "${PORT:-8000}"
Demo sign-in: cenius@cenius.ai / cenius
DONE
